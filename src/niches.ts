export const NICHE_ORDER: NicheId[] = ['salon', 'restaurant', 'dental'];

export function detectNicheId(pathname?: string): NicheId {
  const raw = pathname ?? (typeof window !== 'undefined' ? window.location.pathname : '/');
  const path = raw.replace(/\/+$/, '').toLowerCase();
  const hit = NICHE_ORDER.find((id) => NICHES[id].path === path);
  return hit ?? 'main';
}

export function getNiche(): NicheContent {
  return NICHES[detectNicheId()];
}
